export function TTIcon({
  name,
  size = 20,
  color = COLORS.textPrimary,
  strokeWidth = 1.75,
  ...props
}) {
  const Icon = ICONS[name];
  if (!Icon && __DEV__) console.warn(`TTIcon: nombre de ícono desconocido "${name}".`);

  const Component = Icon || Circle;
  return <Component size={size} color={color} strokeWidth={strokeWidth} {...props} />;
}